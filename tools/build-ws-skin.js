#!/usr/bin/env node
/*
 * Builds public/app/ws-skin.css: the Jamoa (workspace) styles of the new app.
 *
 * js/workspace.js draws the team toolbar, lists, timeline and graph with
 * classes (.ws-bar, .ws-team-btn, .ws-viewbtn, .ws-sec, .ws-load ...) that
 * the dashboard styles in css/dashboard.css under #db-root. The new app has
 * no #db-root, so those rules did not apply and the section showed raw
 * buttons in Space Grotesk. This copies every rule that styles a .ws class,
 * rescopes it from #db-root to .ws-host, and maps the dashboard tokens and
 * font to the app's (Golos Text, light/dark).
 *
 * Run after css/dashboard.css changes:  node tools/build-ws-skin.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'public');
const SOURCES = ['dashboard.css', 'dashboard-ai.css'];
const src = SOURCES.map(f => fs.readFileSync(path.join(root, 'css', f), 'utf8')).join('\n').replace(/\/\*[\s\S]*?\*\//g, '');

function parse(txt) {
  const out = [];
  let i = 0;
  while (i < txt.length) {
    const j = txt.indexOf('{', i);
    if (j < 0) break;
    const sel = txt.slice(i, j).trim();
    let depth = 1, k = j + 1;
    while (depth && k < txt.length) { if (txt[k] === '{') depth++; else if (txt[k] === '}') depth--; k++; }
    out.push({ sel, body: txt.slice(j + 1, k - 1) });
    i = k;
  }
  return out;
}

const SCOPE = '.ws-host';
// Only selectors that style a workspace class; #db-root becomes .ws-host.
function rescope(sel) {
  const parts = sel.split(',').map(s => s.trim()).filter(s => /\.ws[\w-]*/.test(s));
  if (!parts.length) return null;
  return parts.map(s => s.includes('#db-root') ? s.replace(/#db-root/g, SCOPE) : `${SCOPE} ${s}`).join(',\n');
}
// Fonts follow the app; everything else is the dashboard's declaration.
function body(b) { return b.replace(/font-family\s*:\s*'Space Grotesk'[^;]*;?/g, 'font-family:inherit;').trim(); }

const out = [];
for (const r of parse(src)) {
  if (r.sel.startsWith('@media') || r.sel.startsWith('@supports')) {
    const inner = parse(r.body).map(x => { const s = rescope(x.sel); return s ? `  ${s.replace(/\n/g, '\n  ')} { ${body(x.body)} }` : null; }).filter(Boolean);
    if (inner.length) out.push(`${r.sel} {\n${inner.join('\n')}\n}`);
  } else if (!r.sel.startsWith('@')) {
    const s = rescope(r.sel);
    if (s) out.push(`${s} { ${body(r.body)} }`);
  }
}

const head = `/* GENERATED by tools/build-ws-skin.js from css/dashboard.css + css/dashboard-ai.css — do not edit by hand.
   Jamoa (workspace) styles for the new app, scoped to .ws-host, in the app's font and colours. */
.ws-host {
  --ink: var(--fg); --muted-dim: var(--faint); --panel-solid: var(--surface); --panel-hover: var(--panel);
  --brand: var(--cta); --brand-2: var(--cta-dark); --brand-soft: var(--accent-soft); --brand-border: var(--line);
  --shadow: var(--shadow-sm); --shadow-hover: var(--shadow-sm); --danger: var(--bad);
  font-family: var(--sans); color: var(--fg);
}
/* css/workspace.css draws the rest (.ws-btn, .ws-field, modals, timeline) with its own --ws-* colours:
   the app's palette and font instead of the old dashboard's. */
.ws-host .workspace-app {
  --ws-canvas: transparent; --ws-aurora: none;
  --ws-panel: var(--surface); --ws-panel-solid: var(--surface); --ws-panel-hover: var(--panel);
  --ws-ink: var(--fg); --ws-ink-soft: var(--fg); --ws-muted: var(--muted); --ws-muted-dim: var(--faint);
  --ws-line: var(--line); --ws-line-strong: var(--line);
  --ws-brand: var(--cta); --ws-brand-2: var(--cta-dark); --ws-brand-soft: var(--accent-soft); --ws-brand-border: var(--line);
  --ws-success: var(--ok); --ws-warning: var(--warn); --ws-danger: var(--bad);
  --ws-shadow: var(--shadow-sm);
  font-family: var(--sans); background: transparent; color: var(--fg);
  padding: 20px 28px 40px;
}
.ws-host .workspace-app h1, .ws-host .workspace-app h2, .ws-host .workspace-app h3,
.ws-host .workspace-app [data-mono] { font-family: var(--sans); }
`;

const tail = `
/* The dashboard sizes the board under its own header and tab bar; the app has a 60px top bar. */
.ws-host .ws { height: calc(100vh - 140px); padding-top: 0; }
/* No coloured side stripes in the app: the task state is a dot, saved notes sit on a soft panel. */
.ws-host .ws-matter-state { border-left: 0; padding-left: 0; display: inline-flex; align-items: center; gap: 7px; }
.ws-host .ws-matter-state::before { content: ""; width: 7px; height: 7px; border-radius: 50%; background: currentColor; }
.ws-host .ws-saved { border-left: 0; padding: 8px 10px; border-radius: 8px; background: var(--panel); }
`;

const file = path.join(root, 'app', 'ws-skin.css');
fs.writeFileSync(file, head + '\n' + out.join('\n') + '\n' + tail);
console.log(`ws-skin.css: ${out.length} rules`);
